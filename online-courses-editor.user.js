  async function restoreBackup(file, tutors=false){
    if(!file || !(tutors?tEditable():editable()) || Unified.occupiedByOther('courses'))return;
    try{
      if(file.size>25*1024*1024)throw fail('Резервная копия больше 25 МБ.');
      const data=JSON.parse(await file.text());
      if(data.version!==1||!Array.isArray(data.rows)||!Array.isArray(data.logs)||!data.settings)throw fail('Неверный формат резервной копии.');
      for(const row of data.rows){
        if(!row||typeof row!=='object'||!Object.hasOwn(LABEL,row.status)||typeof row.key!=='string')throw fail('Некорректная строка очереди.');
        if(!row.invalid){
          const parsed=tutors?tURL(row.url):courseURL(row.url);
          if(parsed.id!==row.id)throw fail('ID строки не совпадает с URL.');
        }
      }
      if(!confirm('Восстановить очередь, журнал и настройки из JSON? Текущая очередь этого раздела будет заменена. Автоматический запуск отключён.'))return;
      data.running=false;data.owner=null;data.paused=true;
      if(tutors){tState={...tEmpty(),...data};tPersist();tRender();}
      else{state={...empty(),...data};persist();render();}
      message('Резервная копия восстановлена. Проверьте очередь и нажмите «Продолжить».');
    }catch(e){message('Восстановление JSON: '+e.message);}
  }

